#!/usr/bin/env python3
"""
sync_sidecar.py — 生成 bundle 的 Python sidecar 最小子集

从仓库的 `youmi/` 包出发，按 **静态 import 闭包** 把 `youmi.mcp.stdio_server`
真正需要的模块复制到 `<bundle>/sidecar/youmi/`，并对包 `__init__.py` 做裁剪：

- 若真实 `__init__.py` 里的 youmi 导入全部落在闭包内 → 原样复制；
- 否则生成最小 stub（只带一行说明），避免 `youmi/__init__.py` 那种
  「导入整个框架」的连带依赖（memory / coordinator / gateway / …）进 bundle。

用法（在仓库根执行）::

    python dsh-plugins/youmi-tool-catalog/scripts/sync_sidecar.py         # 写入
    python dsh-plugins/youmi-tool-catalog/scripts/sync_sidecar.py --check # 只校验漂移
    python dsh-plugins/youmi-tool-catalog/scripts/sync_sidecar.py --verify # 复制后实际 import 校验

`--verify` 用当前解释器在 sidecar/ 下执行
``import youmi.mcp.stdio_server``，失败即退出码非 0（闭包漏依赖会被这一步抓住）。
"""

from __future__ import annotations

import argparse
import ast
import shutil
import subprocess
import sys
from pathlib import Path

# sidecar 的入口模块（其余依赖全部由静态闭包推出）
ROOT_MODULES = ("youmi.mcp.stdio_server",)

STUB_HEADER = (
    '"""Auto-generated by scripts/sync_sidecar.py — sidecar 最小子集的包声明。\n'
    "\n"
    "真实 `youmi/__init__.py` 会 eager 导入整个框架（memory / coordinator /\n"
    "gateway …），不属于 sidecar 需要的能力，因此这里只保留包本身。\n"
    '不要手工编辑：改动 source youmi/ 后重新运行 sync_sidecar.py。\n"""\n'
)


def module_to_file(root: Path, mod: str) -> Path | None:
    parts = mod.split(".")
    if not parts or parts[0] != "youmi":
        return None
    base = root.joinpath(*parts)
    for cand in (base.with_suffix(".py"), base / "__init__.py"):
        if cand.exists():
            return cand
    return None


def resolve_relative(file: Path, root: Path, node: ast.ImportFrom) -> str | None:
    """把 ``from ..x import y`` 解析成绝对模块名"""
    parts = list(file.relative_to(root).with_suffix("").parts)
    pkg = parts[:-1]  # 模块文件与 __init__.py 都取所在目录
    drop = node.level - 1
    if drop > 0:
        if drop >= len(pkg):
            return None
        pkg = pkg[: len(pkg) - drop]
    target = ".".join(["youmi", *pkg[1:]])
    if node.module:
        target = f"{target}.{node.module}"
    return target


def iter_imports(file: Path, root: Path) -> set[str]:
    """文件内出现的全部 youmi.* 模块引用（含 ``from x import y`` 的 y 候选）"""
    tree = ast.parse(file.read_text(encoding="utf-8"), filename=str(file))
    out: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                out.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                target = resolve_relative(file, root, node)
            elif node.module:
                target = node.module
            else:
                continue
            if not target:
                continue
            out.add(target)
            for alias in node.names:
                out.add(f"{target}.{alias.name}")
    return out


def youmi_imports_of(file: Path, root: Path) -> set[str]:
    return {m for m in iter_imports(file, root) if m.split(".")[0] == "youmi"}


def compute_closure(pkg_dir: Path) -> tuple[set[Path], set[Path], set[str]]:
    """静态 import 闭包：返回 (需要复制的 .py 文件, 涉及的包目录, 第三方依赖根)"""
    root = pkg_dir.parent
    files: set[Path] = set()
    packages: set[Path] = set()
    third_party: set[str] = set()
    stack = list(ROOT_MODULES)
    seen: set[str] = set()
    while stack:
        mod = stack.pop()
        if mod in seen:
            continue
        seen.add(mod)
        top = mod.split(".")[0]
        if top != "youmi":
            third_party.add(top)
            continue
        f = module_to_file(root, mod)
        if f is None:
            parent = ".".join(mod.split(".")[:-1])
            if parent.count(".") >= 1:
                stack.append(parent)
            continue
        files.add(f)
        if f.name == "__init__.py":
            packages.add(f.parent)
        for imp in iter_imports(f, root):
            stack.append(imp)
    # 每个被复制文件所在的包目录都需要 __init__.py
    for f in files:
        d = f.parent
        while d != root and len(d.parts) > len(root.parts):
            packages.add(d)
            d = d.parent
    return files, packages, third_party


def copy_file(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dst)


def init_is_self_contained(file: Path, root: Path, closure_files: set[Path]) -> bool:
    """真实 __init__.py 的所有 youmi 导入是否都在闭包文件集内"""
    for mod in youmi_imports_of(file, root):
        f = module_to_file(root, mod)
        if f is None:
            # 属性导入（from youmi.x import SomeName）→ 看父模块
            parent = ".".join(mod.split(".")[:-1])
            f = module_to_file(root, parent) if parent.count(".") >= 1 else None
        if f is None or f not in closure_files:
            return False
    return True


def sync(bundle_dir: Path, repo_root: Path, check_only: bool) -> list[str]:
    pkg_dir = repo_root / "youmi"
    files, packages, third_party = compute_closure(pkg_dir)
    sidecar_dir = bundle_dir / "sidecar"
    target_pkg = sidecar_dir / "youmi"
    actions: list[str] = []

    # 1. 模块文件
    for src in sorted(files):
        rel = src.relative_to(repo_root)
        dst = sidecar_dir / rel
        if src.read_bytes() == (dst.read_bytes() if dst.exists() else b""):
            continue
        actions.append(f"copy {rel.as_posix()}")
        if not check_only:
            copy_file(src, dst)

    # 2. 包 __init__.py：自包含则原样复制，否则生成 stub
    for pkg in sorted(packages):
        src = pkg / "__init__.py"
        rel = src.relative_to(repo_root)
        dst = sidecar_dir / rel
        if src.exists() and init_is_self_contained(src, repo_root, files):
            if src.read_bytes() == (dst.read_bytes() if dst.exists() else b""):
                continue
            actions.append(f"copy {rel.as_posix()}")
            if not check_only:
                copy_file(src, dst)
            continue
        content = STUB_HEADER.encode("utf-8")
        if dst.exists() and dst.read_bytes() == content:
            continue
        actions.append(f"stub {rel.as_posix()}")
        if not check_only:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(content)

    # 3. 清理已不在闭包内的陈旧文件
    if target_pkg.exists() and not check_only:
        keep = {(sidecar_dir / f.relative_to(repo_root)) for f in files}
        keep |= {sidecar_dir / (p / "__init__.py").relative_to(repo_root) for p in packages}
        for existing in target_pkg.rglob("*.py"):
            if existing not in keep:
                existing.unlink()
                actions.append(f"prune {existing.relative_to(sidecar_dir).as_posix()}")

    print(
        f"sidecar subset: {len(files)} modules, {len(packages)} packages, "
        f"third-party roots: {sorted(third_party)}",
    )
    for a in actions:
        print("  ", a)
    if not actions:
        print("   (up to date)")
    return actions


def verify(sidecar_dir: Path, python: str) -> None:
    """在 sidecar/ 下真的 import 一次入口，验证闭包完整"""
    code = "import youmi.mcp.stdio_server as m; print('import ok', m.__file__)"
    proc = subprocess.run(
        [python, "-X", "utf8", "-c", code],
        cwd=str(sidecar_dir), capture_output=True, text=True,
    )
    if proc.returncode != 0:
        print(proc.stdout)
        print(proc.stderr, file=sys.stderr)
        raise SystemExit(f"sidecar import verification FAILED (exit {proc.returncode})")
    print("  ", proc.stdout.strip())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--bundle", default=None,
        help="bundle 目录（默认: 本脚本上级目录，即 dsh-plugins/youmi-tool-catalog）",
    )
    parser.add_argument("--check", action="store_true", help="只报告漂移，不写入")
    parser.add_argument("--verify", action="store_true", help="写入后用当前解释器 import 校验")
    parser.add_argument("--python", default=sys.executable, help="--verify 使用的解释器")
    args = parser.parse_args()

    bundle_dir = Path(args.bundle).resolve() if args.bundle else Path(__file__).resolve().parents[1]
    repo_root = bundle_dir.parents[1]
    if not (repo_root / "youmi").is_dir():
        raise SystemExit(f"repo root not detected from {bundle_dir} (expected <root>/youmi)")

    sync(bundle_dir, repo_root, check_only=args.check)
    if args.verify:
        verify(bundle_dir / "sidecar", args.python)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
